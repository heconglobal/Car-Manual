import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import * as T from 'three';
import {sourceFingerprint} from './source-fingerprint.mjs';
const before=sourceFingerprint();
globalThis.document={createElement:()=>({getContext:()=>({createImageData:(w,h)=>({data:new Uint8ClampedArray(w*h*4)}),putImageData(){},fillRect(){},strokeRect(){},fillText(){}})})};
const {createWiperDetail}=await import('../src/wiper-detail.js');
const {wiperParts}=await import('../src/wiper-catalog.js');
const {detailAvailable}=await import('../src/inspection-catalog.js');
const {defaultConfiguration}=await import('../src/configuration.js');
const {root,groups}=createWiperDetail();root.updateMatrixWorld(true);
const checks=[];let triangles=0;
assert.equal(groups.size,wiperParts.length);assert.equal(new Set(wiperParts.map(p=>p.id)).size,wiperParts.length);
for(const p of wiperParts){const g=groups.get(p.id);assert(g.children.length,p.id);g.traverse(m=>{if(!m.isMesh)return;assert.equal(m.userData.partId,p.id);assert(m.geometry.attributes.position.array.every(Number.isFinite),p.id);assert(m.matrixWorld.determinant()>0,p.id);triangles+=(m.geometry.index?.count||m.geometry.attributes.position.count)/3;if(p.option){assert.equal(m.userData.option,p.option);assert.equal(m.userData.value,p.value);}});}
checks.push('Every selection has finite positive-transform geometry with correct picking and option metadata');
const visible=delayWipers=>wiperParts.filter(p=>detailAvailable(p,{...defaultConfiguration,delayWipers})).map(p=>p.id);
assert(visible(false).includes('ww-motor-armature'));assert(!visible(false).includes('ww-pulse-board'));
assert(visible(true).includes('ww-pulse-board'));assert(!visible(true).includes('ww-motor-armature'));
checks.push('Standard and CD4 motor alternatives are exclusive; common linkage and washer stay visible');
for(const p of wiperParts)assert(p.sourceUrl.includes('#page='));
assert.equal(wiperParts.find(p=>p.id==='ww-pulse-motor').partNumber,'22062913');
assert.equal(wiperParts.find(p=>p.id==='ww-motor-housing').partNumber,'22062915');
checks.push('Original application table distinguishes standard 1984–85 from CD4 1985–87');
const bounds=id=>new T.Box3().setFromObject(groups.get(id));
assert(bounds('ww-washer-bottle').max.x<0,'washer bottle must remain on driver side');
assert(bounds('ww-washer-pump').max.y<bounds('ww-washer-bottle').max.y-.1,'pump must be beneath bottle');
assert(bounds('ww-pivot-left').getCenter(new T.Vector3()).x<0);
assert(bounds('ww-pivot-right').getCenter(new T.Vector3()).x>0);
checks.push('Left/right pivots and bottom-mounted driver-side washer pump retain original handedness');
const ray=new T.Raycaster(new T.Vector3(-.43,.530,-1.29),new T.Vector3(0,-1,0));
const hits=ray.intersectObjects(groups.get('ww-washer-bottle').children,false);
assert(hits.every(hit=>hit.point.y<.40),'filler neck must open into the bottle');
checks.push('Washer filler neck is open; cap is independently selectable');
const after=sourceFingerprint();assert.equal(after,before,'source changed during audit');
const directory='artifacts/completion-wipers/'+new Date().toISOString().replaceAll(':','-');await mkdir(directory,{recursive:true});
const report={date:new Date().toISOString(),sourceSha256:after,status:'passed',selections:wiperParts.length,triangles,standardVisible:visible(false).length,pulseVisible:visible(true).length,checks,limits:'Static reconstructed geometry and software identity checks. No measured tooling, operating sweep, electrical/park/delay calibration, pump internals, factory routing or owner/workshop acceptance.'};
await writeFile(directory+'/audit.json',JSON.stringify(report,null,2)+'\n',{flag:'wx'});console.log(JSON.stringify({...report,report:directory+'/audit.json'},null,2));
