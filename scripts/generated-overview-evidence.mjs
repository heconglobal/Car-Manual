import assert from 'node:assert/strict';
import {readFile,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {gunzipSync} from 'node:zlib';

const sha256=bytes=>createHash('sha256').update(bytes).digest('hex');
export function parseGeneratedOverviewDescriptor(source,path){
 const manifest=JSON.parse(source.slice(source.indexOf('{'),source.lastIndexOf('}')+1));
 if(!manifest.url)return null; // Preserved placeholder before first generation.
 assert(source.startsWith('// Generated by scripts/build-overview.mjs;'),'Unattributed model descriptor: '+path);
 assert.equal(manifest.format,1,'Unknown generated model format');
 for(const field of ['sha256','inputsSha256'])assert(/^[a-f0-9]{64}$/.test(manifest[field]),'Missing generator '+field);
 assert.equal(manifest.url,'/models/overview-'+manifest.sha256.slice(0,24)+'.bin.gz','Unexpected generated asset path');
 for(const field of ['bytes','decodedBytes','parts','meshes','triangles'])assert(Number.isSafeInteger(manifest[field])&&manifest[field]>0,'Invalid generator '+field);
 return{manifest,descriptor:path};
}

export async function generatedOverviewDescriptors(){
 const paths=['src/overview-manifest.js'];
 for(const entry of await readdir('preserved',{withFileTypes:true}))if(entry.isDirectory()&&entry.name.endsWith('-before-overview-regeneration'))paths.push('preserved/'+entry.name+'/src/overview-manifest.js');
 const known=new Map();
 for(const path of paths){
  const record=parseGeneratedOverviewDescriptor(await readFile(path,'utf8'),path);
  if(record&&!known.has(record.manifest.url.slice(1)))known.set(record.manifest.url.slice(1),record);
 }
 return known;
}

export function inspectGeneratedOverview(buffer,record){
 const {manifest,descriptor}=record;
 assert.equal(buffer.length,manifest.bytes,'Generated overview compressed length differs from descriptor');
 assert.equal(sha256(buffer),manifest.sha256,'Generated overview differs from its preserved generator output');
 const decoded=gunzipSync(buffer,{maxOutputLength:manifest.decodedBytes});
 assert.equal(decoded.length,manifest.decodedBytes,'Generated overview decoded length differs from descriptor');
 if(manifest.decodedSha256)assert.equal(sha256(decoded),manifest.decodedSha256,'Generated overview decoded hash differs');
 assert.equal(decoded.subarray(0,8).toString(),'FIEROV01','Unexpected model payload instead of native generated overview');
 const end=12+decoded.readUInt32LE(8);assert(end<=decoded.length,'Truncated generated overview metadata');
 const metadata=JSON.parse(decoded.subarray(12,end).toString());assert.equal(metadata.version,1);
 assert.equal(metadata.groups.length,manifest.parts,'Generated overview group inventory differs');
 const meshes=metadata.groups.flatMap(group=>group.meshes);
 assert.equal(meshes.length,manifest.meshes,'Generated overview mesh inventory differs');
 const triangles=meshes.reduce((sum,mesh)=>sum+(mesh.index?mesh.index.length:mesh.attributes.position.length/mesh.attributes.position.itemSize)/3,0);
 assert.equal(triangles,manifest.triangles,'Generated overview triangle inventory differs');
 for(const texture of metadata.textures)assert(['text','grain'].includes(texture.recipe?.kind),'Generated overview contains an imported texture instead of a procedural recipe');
 return{file:manifest.url.slice(1),descriptor,sourceInputsSha256:manifest.inputsSha256,sha256:manifest.sha256,bytes:buffer.length,decodedBytes:decoded.length,parts:manifest.parts,meshes:manifest.meshes,triangles,textureRecipes:metadata.textures.length};
}
